// Bake the LIFE town navmesh at build time (recast-navigation, Node) -> src/life/navmesh.gen.ts: walkable triangles of the
// ground around every building footprint, quantized to 1/4 ft. The game never loads recast's ~1 MB wasm: src/life/navgraph.ts
// walks the baked triangles (A* over triangle adjacency + funnel), a few KB. Re-run after changing places.ts.
//   npx tsx scripts/life/navbake.ts
import fs from "node:fs";
import { init, getNavMeshPositionsAndIndices } from "recast-navigation";
import { generateSoloNavMesh } from "recast-navigation/generators";
import { townGeometry } from "../../src/client/nav";
import { PLACES, WORLD } from "../../src/life/places";

await init();
const g = townGeometry(PLACES as any, WORLD, 20);
const r: any = generateSoloNavMesh(g.positions, g.indices, { cs: 0.5, ch: 0.25, walkableRadius: 3, walkableClimb: 2, walkableHeight: 8, maxEdgeLen: 60, maxSimplificationError: 1.0, minRegionArea: 30, mergeRegionArea: 400, maxVertsPerPoly: 3 } as any);
if (!r.success) throw new Error("navmesh failed " + r.error);
const [pos, idx] = getNavMeshPositionsAndIndices(r.navMesh);
// keep ground triangles only (drop roof islands), dedupe vertices on the quantized grid
const Q = 4,
  key = new Map<string, number>(),
  V: number[] = [],
  T: number[] = [];
const vid = (i: number) => {
  const x = Math.round(pos[i * 3] * Q),
    z = Math.round(pos[i * 3 + 2] * Q),
    k = x + "," + z;
  let v = key.get(k);
  if (v == null) (v = V.length / 2), key.set(k, v), V.push(x, z);
  return v;
};
for (let t = 0; t < idx.length; t += 3) {
  if (Math.max(pos[idx[t] * 3 + 1], pos[idx[t + 1] * 3 + 1], pos[idx[t + 2] * 3 + 1]) > 2) continue;
  const a = vid(idx[t]), b = vid(idx[t + 1]), c = vid(idx[t + 2]);
  if (a !== b && b !== c && a !== c) T.push(a, b, c);
}
const b64 = (a: ArrayBufferView) => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString("base64");
const out = `// GENERATED by scripts/life/navbake.ts (recast-navigation) - do not edit. ${T.length / 3} triangles, ${V.length / 2} vertices.
// v: int16 x,z pairs in 1/${Q} ft; t: uint16 vertex indices (3 per walkable ground triangle).
export const NAVMESH = { q: ${Q}, v: "${b64(new Int16Array(V))}", t: "${b64(new Uint16Array(T))}" };
`;
fs.writeFileSync("src/life/navmesh.gen.ts", out);
console.log(`navbake: ${T.length / 3} triangles, ${V.length / 2} vertices, ${(out.length / 1024).toFixed(1)} KB -> src/life/navmesh.gen.ts`);
process.exit(0);
