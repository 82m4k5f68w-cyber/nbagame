// Bake the trained shot model (assets/ml/shot_mm.json, scripts/ml/train_shot.py) into deterministic game tables:
//   src/core/mmshot.ts                         (TS sim / client)
//   unity/Assets/Scripts/Core/Pose.MM.Gen.cs   (C# twin, same numbers)
//   npx tsx scripts/ml/bake_shot.ts
// Post-processing (fixed, documented in CLAUDE.md "Shot motion matching (v5.6)"):
//   - twist channels (oR oL hR hL) keep only their motion relative to the dip (k = 0): the capture's absolute forearm /
//     humeral twist carries a calibration offset the classic rig poses do not have;
//   - the shooting arm (aR eR sz wR hR oR) is anchored to the classic clip's release pose: offset to the classic curve
//     faded in by smoothstep over k .3 .. RELK and held through the follow-through -> the release point (handPos at
//     launch) stays where the green-window / aim code has always seen it; the gather and rise keep the capture;
//   - cr (crouch) only counts on the floor: the captured dip (clamped to .7) fades into the classic landing crouch;
//   - fadeaway / step-back: the channels the classic fade / step clips define (lean, yaw, legs) stay classic (the CMU
//     set has no real fadeaway), timing and arms from the model.
import fs from "node:fs";
import { CL } from "../../src/core/data";

const R = JSON.parse(fs.readFileSync("assets/ml/shot_mm.json", "utf8"));
const B = R.bake as { ch: string[]; kb: number; types: Record<string, Record<string, number[]>>; dLoad: Record<string, number[]> };
const KB = B.kb;
const CLIPK = ["aR", "eR", "aL", "eL", "tL", "tR", "kL", "kR", "ln", "sz", "cr", "rz", "ty", "wR", "wL", "zL", "oR", "oL"];
const CHN = [...CLIPK, "hR", "hL"]; // baked channel order (MM_CH)
const RELK: Record<string, number> = { cs: 0.7, pull: 0.7, deep: 0.7, fade: 0.7, step: 0.7, quick: 0.46 };
const CLASSIC: Record<string, string> = { cs: "jump", pull: "jump", deep: "jump", fade: "fade", step: "step", quick: "quick" };
// (same smoothstep keyframe sampler as pose.ts smp)
function smp(a: number[] | undefined, k: number) {
  if (!a) return null;
  if (k <= a[0]) return a[1];
  for (let i = 2; i < a.length; i += 2)
    if (k <= a[i]) {
      const u = (k - a[i - 2]) / (a[i] - a[i - 2]),
        s = u * u * (3 - 2 * u);
      return a[i - 1] + (a[i + 1] - a[i - 1]) * s;
    }
  return a[a.length - 1];
}
const classic = (kind: string, ch: string, k: number) => smp(CL[kind][ch], k) ?? smp(CL.jump[ch], k) ?? 0;
const sst = (x: number) => {
  const u = Math.max(0, Math.min(1, x));
  return u * u * (3 - 2 * u);
};
const ARM = ["aR", "eR", "sz", "wR", "hR", "oR"],
  TWIST = ["oR", "oL", "hR", "hL"];
const r3 = (v: number) => Math.round(v * 1000) / 1000 + 0; // (+0: no -0 in the source)
const out: Record<string, number[][]> = {};
for (const [t, tb] of Object.entries(B.types)) {
  const rk = RELK[t],
    ck = CLASSIC[t],
    rows: number[][] = [];
  for (const ch of CHN) {
    const row: number[] = [];
    for (let i = 0; i < KB; i++) {
      const k = i / (KB - 1);
      let v = tb[ch] ? tb[ch][i] : 0;
      if (TWIST.includes(ch)) v -= tb[ch][0];
      if (ARM.includes(ch)) {
        const w = sst((k - 0.3) / (rk - 0.3)),
          c = ch === "hR" ? 0 : classic(ck, ch, k);
        v += (c - v) * w;
      }
      if (ch === "cr") {
        const w = sst(k / 0.2);
        v = Math.max(0, Math.min(0.7, v)) * (1 - w) + classic(ck, "cr", k) * w;
      }
      if ((t === "fade" || t === "step") && CL[ck][ch] && !ARM.includes(ch)) v = classic(ck, ch, k);
      row.push(r3(v));
    }
    rows.push(row);
  }
  out[t] = rows;
}
const dLoad = CHN.map((ch) => (B.dLoad[ch] ? B.dLoad[ch].map((v, i) => r3(ch === "cr" ? v * (1 - sst(i / (KB - 1) / 0.2)) : v)) : new Array(KB).fill(0)));
const TYPES = Object.keys(out);
const val = R.val_low,
  vau = R.val_upp;
const hdr = `// GENERATED by scripts/ml/bake_shot.ts from assets/ml/shot_mm.json (scripts/ml/train_shot.py) - do not edit by hand.
// Shot motion matching (v5.6, cfg.MM): jump-shot curves learned from CMU motion capture (mocap.cs.cmu.edu, NSF
// EIA-0196217, free for research and commercial use; cgspeed BVH by B. Hahne): 5 basketball shots (06_14, 06_15,
// 124_03, 124_04, 124_05) + 61 two-foot jumps (16, 118, 13, 49, 02), retarget scripts/mocap/bvh31.ts + shots.ts.
// Phase-conditioned MLPs, grouped leave-one-clip-out RMSE (rad): lower body ${val.rmse_rad_all.mlp.toFixed(3)} (1-NN motion matching
// ${val.rmse_rad_all.mm1.toFixed(3)}, mean ${val.rmse_rad_all.mean.toFixed(3)}), upper body ${vau.rmse_rad_all.mlp.toFixed(3)} (1-NN ${vau.rmse_rad_all.mm1.toFixed(3)}, mean ${vau.rmse_rad_all.mean.toFixed(3)}).
// Tables: MM_KB uniform keys over the clip phase k (0 dip .. RELK release .. 1), sampled Catmull-Rom (pose.ts mmSample).`;
const ts = `${hdr}
/** Baked channels (rows of every table). */
export const MM_CH = ${JSON.stringify(CHN)};
export const MM_KB = ${KB};
/** Shot types: catch-and-shoot, pull-up, deep three, fadeaway, step-back, quick release. */
export const MM_TYPES = ${JSON.stringify(TYPES)};
/** MM_T[type][channel][key] (rad; cr in crouch units). */
export const MM_T: Record<string, number[][]> = {
${TYPES.map((t) => `  ${t}: [\n${out[t].map((r) => `    [${r.join(", ")}],`).join("\n")}\n  ],`).join("\n")}
};
/** Learned load axis (d curve per form step: deeper dip / more leg), added x the player's load (-1.5 .. 1.5). */
export const MM_DLOAD: number[][] = [
${dLoad.map((r) => `  [${r.join(", ")}],`).join("\n")}
];
`;
fs.writeFileSync("src/core/mmshot.ts", ts);
const n = (v: number) => (Number.isInteger(v) ? v.toFixed(1) : String(v));
const cs = `${hdr.replace(/scripts\/ml\/bake_shot.ts/, "scripts/ml/bake_shot.ts (C# twin of src/core/mmshot.ts)")}
namespace Hoops.Core {
    public static partial class Pose {
        public static readonly string[] MM_CH = { ${CHN.map((c) => JSON.stringify(c)).join(", ")} };
        public const int MM_KB = ${KB};
        public static readonly string[] MM_TYPES = { ${TYPES.map((c) => JSON.stringify(c)).join(", ")} };
        public static readonly double[][][] MM_T = {
${TYPES.map((t) => `            new double[][] { // ${t}\n${out[t].map((r) => `                new double[] { ${r.map(n).join(", ")} },`).join("\n")}\n            },`).join("\n")}
        };
        public static readonly double[][] MM_DLOAD = {
${dLoad.map((r) => `            new double[] { ${r.map(n).join(", ")} },`).join("\n")}
        };
    }
}
`;
fs.writeFileSync("unity/Assets/Scripts/Core/Pose.MM.Gen.cs", cs);
console.log("wrote src/core/mmshot.ts", ts.length, "bytes; Pose.MM.Gen.cs", cs.length, "bytes; types", TYPES.join(" "));
