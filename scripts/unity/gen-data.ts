// Generates unity/Assets/Scripts/Core/Data.Gen.cs from src/core/data.ts + mocap.ts (the single source of truth).
//   npx tsx scripts/unity/gen-data.ts
import fs from "node:fs";
import { TM, SK, SP, OV, PRE, CL, CK, SIG } from "../../src/core/data";
import { MC_CH, MC_RAW, MC_SHOT, MC_JUMP } from "../../src/core/mocap";
const n = (v: number) => (Number.isInteger(v) ? v.toFixed(1) : String(v)); // double literal
const s = (v: string) => JSON.stringify(v);
const arr = (a: number[]) => `new double[] { ${a.map(n).join(", ")} }`;
const clip = (c: Record<string, number[]>) => `new Clip { ${Object.entries(c).map(([k, v]) => `[${s(k)}] = ${arr(v)}`).join(", ")} }`;
const o: string[] = [];
o.push("// GENERATED by scripts/unity/gen-data.ts from src/core/data.ts + mocap.ts - do not edit by hand.");
o.push("using System.Collections.Generic;");
o.push("namespace Hoops.Core {");
o.push("public sealed class Clip : Dictionary<string, double[]> { }");
o.push("public static partial class Data {");
o.push("  public static readonly Team[] TM = {");
for (const [name, col, ps] of TM)
  o.push(`    new Team(${s(name)}, ${s(col)}, new[] {\n${ps.map((p) => `      new Tuple(${s(p[0])}, ${p.slice(1, 7).join(", ")}, ${s(p[7])}, ${p[8]}, ${p[9]}, ${n(p[10])}, ${n(p[11])}, ${p[12]})`).join(",\n")} }),`);
o.push("  };");
o.push(`  public static readonly string[] SK = { ${SK.map(s).join(", ")} };`);
o.push(`  public static readonly double[][] SP = { ${SP.map(arr).join(", ")} };`);
o.push(`  public static readonly Dictionary<string, int> OV = new() { ${Object.entries(OV).map(([k, v]) => `[${s(k)}] = ${v}`).join(", ")} };`);
o.push(`  public static readonly Dictionary<string, double[]> PRE = new() { ${Object.entries(PRE).map(([k, v]) => `[${s(k)}] = ${arr(v)}`).join(", ")} };`);
o.push("  public static readonly Dictionary<string, Clip> CL = new() {");
for (const [k, c] of Object.entries(CL)) o.push(`    [${s(k)}] = ${clip(c)},`);
o.push("  };");
o.push(`  public static readonly string[] CK = { ${CK.map(s).join(", ")} };`);
// signature overrides applied over the hashed form
o.push("  static void ApplySig(string name, Form f) {");
o.push("    switch (name) {");
for (const [name, sg] of Object.entries(SIG)) {
  const set = Object.entries(sg).map(([k, v]) =>
    k === "ce" ? `f.ce = new[] { ${(v as number[]).join(", ")} };` : k === "face" ? `f.face = new Face { ${Object.entries(v as any).map(([a, b]) => `${a} = ${n(b as number)}`).join(", ")} };` : `f.${k} = ${n(v as number)};`,
  );
  o.push(`      case ${s(name)}: ${set.join(" ")} break;`);
}
o.push("    }");
o.push("  }");
o.push(`  public static readonly string[] MC_CH = { ${MC_CH.map(s).join(", ")} };`);
o.push("  public static readonly Dictionary<string, McRaw> MC_RAW = new() {");
for (const [k, v] of Object.entries(MC_RAW)) o.push(`    [${s(k)}] = new McRaw(${n(v.speed)}, ${n(v.stride)}, ${v.dir}, ${v.n}, ${s(v.d)}),`);
o.push("  };");
o.push(`  public static readonly Clip MC_SHOT = ${clip(MC_SHOT)};`);
o.push(`  public static readonly Clip MC_JUMP = ${clip(MC_JUMP)};`);
o.push("}");
o.push("}");
fs.writeFileSync("unity/Assets/Scripts/Core/Data.Gen.cs", o.join("\n") + "\n");
console.log("wrote", o.length, "lines");
