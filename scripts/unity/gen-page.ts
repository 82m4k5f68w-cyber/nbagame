// Generates the data + CSS of the Unity WebGL template (unity/Assets/WebGLTemplates/Hoops/TemplateData) from the
// browser game's single sources of truth, so the Unity page looks and reads like the HTML game:
//   roster.js  <- src/core/data.ts (TM tuples + OVR), src/core/modes.ts (CLUTCH), src/client/modesui.ts (MODES)
//   hubdata.js <- src/client/main.ts (update LOG, controls K1..K5)
//   hub.css / game.css <- the two <style> blocks of index.html (hub page / game overlays)
//   tokens.css / kit.css / fonts <- src/client/ui (UI v6 design tokens + shared components)
//   npx tsx scripts/unity/gen-page.ts
import fs from "node:fs";
import { TM, ov2 } from "../../src/core/data";
import { CLUTCH } from "../../src/core/modes";
import { BADGE } from "../../src/core/sim";
import { MODES, MDESC } from "../../src/client/modesui";

const OUT = "unity/Assets/WebGLTemplates/Hoops/TemplateData";
fs.mkdirSync(OUT, { recursive: true });
const head = "// GENERATED by scripts/unity/gen-page.ts - do not edit by hand.\n";

// roster: [team name, colour, [[...tuple (13 fields), ovr, badge codes]]] (badges: sim.ts BADGE, from ratings)
const badges = (p: any[]) => {
  const pl: any = { n: p[0], c: p[1], i: p[2], s: p[3], d: p[4], j: p[5], ht: p[10] };
  return Object.keys(BADGE).filter((b) => BADGE[b][1](pl));
};
const tm = TM.map(([n, c, ps]) => [n, c, ps.map((p) => [...p, ov2(p), badges(p)])]);
const badgeN = Object.fromEntries(Object.entries(BADGE).map(([k, v]) => [k, v[0]]));
const clutch = CLUTCH.map((c) => ({ n: c.n, d: c.d }));
// Season needs the browser's schedule screens (not ported to the Unity page yet)
const modes = MODES.filter(([k]) => k !== "season").map((m) => [...m, ...(MDESC[m[0]] || ["", "#2a2f6a"])]); // [key, icon, name, line, accent]
fs.writeFileSync(`${OUT}/roster.js`, head + `window.H2K_DATA=${JSON.stringify({ TM: tm, BADGE: badgeN, CLUTCH: clutch, MODES: modes })};\n`);

// hub texts: slice the literal arrays out of main.ts and evaluate them (plain data, no code)
const main = fs.readFileSync("src/client/main.ts", "utf8");
const lit = (name: string) => {
  const a = main.indexOf(`const ${name}=[`);
  if (a < 0) throw new Error("main.ts: no " + name);
  const b = main.indexOf("];\n", a);
  return new Function(`return ${main.slice(a + `const ${name}=`.length, b + 1)}`)();
};
const hub = { LOG: lit("LOG"), K1: lit("K1"), K2: lit("K2"), K3: lit("K3"), K4: lit("K4"), K5: lit("K5") };
fs.writeFileSync(`${OUT}/hubdata.js`, head + `window.H2K_HUB=${JSON.stringify(hub)};\n`);

// CSS: index.html <style id="hcss"> (hub) and <style id="gcss"> (game overlays)
const html = fs.readFileSync("index.html", "utf8");
const css = (id: string) => {
  const m = html.match(new RegExp(`<style id="${id}"[^>]*>([\\s\\S]*?)</style>`));
  if (!m) throw new Error("index.html: no style " + id);
  return m[1].trim() + "\n";
};
fs.writeFileSync(`${OUT}/hub.css`, "/* GENERATED by scripts/unity/gen-page.ts from index.html #hcss - do not edit by hand. */\n" + css("hcss"));
fs.writeFileSync(`${OUT}/game.css`, "/* GENERATED by scripts/unity/gen-page.ts from index.html #gcss - do not edit by hand. */\n" + css("gcss"));
// UI v6 design tokens + shared components (src/client/ui): copied as-is, with the display font next to them
fs.copyFileSync("src/client/ui/tokens.css", `${OUT}/tokens.css`);
fs.copyFileSync("src/client/ui/kit.css", `${OUT}/kit.css`);
fs.mkdirSync(`${OUT}/fonts`, { recursive: true });
for (const f of fs.readdirSync("src/client/ui/fonts")) fs.copyFileSync(`src/client/ui/fonts/${f}`, `${OUT}/fonts/${f}`);
console.log("wrote", OUT, `(${tm.length} teams, ${hub.LOG.length} releases, ${modes.length} modes)`);
